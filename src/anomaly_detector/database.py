"""Database engine and compatibility connections for SQLite and PostgreSQL."""

from __future__ import annotations

import os
import re
import sqlite3
from pathlib import Path
from typing import Any, Iterable

from sqlalchemy import create_engine, text
from sqlalchemy.engine import Connection, Engine
from sqlalchemy.exc import SQLAlchemyError

DEFAULT_SQLITE_PATH = Path("data/telemetry.sqlite")
_ENGINES: dict[str, Engine] = {}


def database_target(target: str | Path | None = None) -> str:
    value = target or os.getenv("DATABASE_URL") or os.getenv("ANOMALY_DATABASE_PATH")
    if value:
        return str(value)
    return str(DEFAULT_SQLITE_PATH)


def is_postgresql(target: str | Path | None = None) -> bool:
    return database_target(target).startswith(("postgresql://", "postgres://", "postgresql+"))


def _engine_url(target: str | Path) -> str:
    value = database_target(target)
    if is_postgresql(value):
        return value.replace("postgres://", "postgresql+psycopg://", 1).replace(
            "postgresql://", "postgresql+psycopg://", 1,
        )
    path = Path(value)
    path.parent.mkdir(parents=True, exist_ok=True)
    return f"sqlite:///{path.resolve().as_posix()}"


def _engine(target: str | Path) -> Engine:
    url = _engine_url(target)
    if url not in _ENGINES:
        kwargs: dict[str, Any] = {"future": True, "pool_pre_ping": True}
        if url.startswith("sqlite://"):
            kwargs["connect_args"] = {"check_same_thread": False, "timeout": 30}
        else:
            kwargs.update({"pool_size": 2, "max_overflow": 0, "pool_timeout": 30})
        _ENGINES[url] = create_engine(url, **kwargs)
    return _ENGINES[url]


class CompatRow(dict):
    """Provide sqlite3.Row-style key and positional access."""

    def __init__(self, keys: Iterable[str], values: Iterable[Any]):
        super().__init__(zip(keys, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def _postgres_sql(sql: str) -> str:
    sql = re.sub(r"\bBEGIN\s+IMMEDIATE\b", "BEGIN", sql, flags=re.IGNORECASE)
    if "INSERT OR REPLACE INTO detection_configurations" in sql.upper():
        sql = re.sub(
            r"INSERT\s+OR\s+REPLACE\s+INTO\s+detection_configurations",
            "INSERT INTO detection_configurations",
            sql,
            flags=re.IGNORECASE,
        )
        return sql + " ON CONFLICT (name) DO UPDATE SET payload_json = EXCLUDED.payload_json, updated_at_utc = EXCLUDED.updated_at_utc"
    sql = re.sub(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", sql, flags=re.IGNORECASE)
    if sql.lstrip().upper().startswith("INSERT INTO"):
        sql += " ON CONFLICT DO NOTHING"
    sql = re.sub(r"\bORDER BY ([a-z_]+), rowid\b", r"ORDER BY \1", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bORDER BY rowid\b", "ORDER BY 1", sql, flags=re.IGNORECASE)
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql)
    return sql


def _bind_parameters(sql: str, parameters: Any) -> tuple[str, dict[str, Any]]:
    if parameters is None:
        return sql, {}
    if isinstance(parameters, dict):
        return sql, parameters
    values = tuple(parameters) if not isinstance(parameters, (str, bytes)) else (parameters,)
    index = 0

    def replace(_match):
        nonlocal index
        name = f"p{index}"
        index += 1
        return f":{name}"

    return re.sub(r"\?", replace, sql), {f"p{i}": value for i, value in enumerate(values)}


class DatabaseResult:
    def __init__(self, result):
        self._result = result
        self.rowcount = result.rowcount

    def fetchone(self):
        row = self._result.fetchone()
        return _compat_row(row) if row is not None else None

    def fetchall(self):
        return [_compat_row(row) for row in self._result.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


def _compat_row(row) -> CompatRow:
    return CompatRow(row._mapping.keys(), row)


class DatabaseConnection:
    def __init__(self, connection: Connection, postgres: bool):
        self._connection = connection
        self.postgres = postgres

    def execute(self, sql: str, parameters: Any = None) -> DatabaseResult:
        command = sql.strip()
        if command.upper().startswith("PRAGMA"):
            if self.postgres:
                return DatabaseResult(_EmptyResult())
            command = command
        elif self.postgres:
            command = _postgres_sql(command)
        command, bound = _bind_parameters(command, parameters)
        try:
            return DatabaseResult(self._connection.execute(text(command), bound))
        except SQLAlchemyError as exc:
            raise sqlite3.OperationalError(str(exc)) from exc

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.close()


class _EmptyResult:
    rowcount = -1

    def fetchone(self):
        return None

    def fetchall(self):
        return []


def connect(target: str | Path) -> DatabaseConnection:
    postgres = is_postgresql(target)
    try:
        connection = _engine(target).connect().execution_options(isolation_level="AUTOCOMMIT")
        wrapper = DatabaseConnection(connection, postgres)
        if not postgres:
            wrapper.execute("PRAGMA busy_timeout = 30000")
            wrapper.execute("PRAGMA foreign_keys = ON")
        return wrapper
    except SQLAlchemyError as exc:
        raise sqlite3.OperationalError(str(exc)) from exc


def dispose_engines() -> None:
    for engine in _ENGINES.values():
        engine.dispose()
    _ENGINES.clear()
